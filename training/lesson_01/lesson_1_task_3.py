# Запрашиваем имя и сохраняем его в переменную first_name
# Программа здесь "зависнет" и будет ждать ввода
first_name = input("Введите ваше имя: ")

# Запрашиваем фамилию и сохраняем в last_name
last_name = input("Введите вашу фамилию: ")

# Выводим результат.
# Используем f-строку (буква f перед кавычками)
# Она позволяет вставить переменные внутрь текста
print(f"Вас зовут: {last_name} {first_name}")
